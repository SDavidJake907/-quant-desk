"""Which days the market is shut, and which closures nobody will flatten.

    python scripts/market_calendar.py                    # the next 12 months
    python scripts/market_calendar.py --through 2027-06-30
    python scripts/market_calendar.py --write MARKET_CALENDAR.md

READ-ONLY, and outside the frozen trading path. It submits no order and reads
the broker calendar only.

WHY IT EXISTS
The holidays are not in this repo and should not be. They are in the broker's
calendar, which is the same source `flatten.py` already trusts to find today's
closing bell, and a copy of them here would be correct until the first time an
exchange changed one. What was missing is not the data but the question:
**which closures does the Friday-only flatten fail to cover?**

`wind_down_from_weekday` stops new entries on Friday, and both flatten triggers
are registered Friday-only. In a week whose Friday is a holiday, Thursday is
the last session before a multi-day close and neither rule notices. This prints
those dates so they can be covered by hand while the evaluation window is open,
because the real fix changes `policy.py` and `flatten.py` and would end it.

Run it when the year's calendar is published, and after any exchange change.
"""

from __future__ import annotations

import argparse
import asyncio
from datetime import date, timedelta

import httpx

from scanner.config import settings
from scanner.execution.alpaca import Alpaca, BrokerError
from scanner.sources.market_calendar import (
    Session,
    closures,
    holidays,
    parse_sessions,
    unflattened,
)

DIM, BOLD, RESET = "\033[2m", "\033[1m", "\033[0m"
GREEN, RED, YELLOW, CYAN = "\033[32m", "\033[31m", "\033[33m", "\033[36m"


async def fetch(start: date, end: date) -> tuple[Session, ...]:
    async with httpx.AsyncClient() as client:
        broker = Alpaca(settings.alpaca_key_id, settings.alpaca_secret_key, client)
        payload = await broker._get(
            "/v2/calendar", start=start.isoformat(), end=end.isoformat(),
        )
    return parse_sessions(payload)


def _render(sessions: tuple[Session, ...], start: date, end: date) -> str:
    """The reference document, generated so it cannot drift from the broker."""
    shut = holidays(sessions, start, end)
    early = [s for s in sessions if s.is_early_close]
    missed = unflattened(sessions)
    lines = [
        "# Market calendar",
        "",
        f"Generated by `scripts/market_calendar.py` from Alpaca's `/v2/calendar`",
        f"on {date.today():%Y-%m-%d}, covering {start} to {end}.",
        "",
        "**This file is a report, not a source of truth.** Nothing reads it.",
        "The live flatten asks the broker for each day's closing bell, which is",
        "why it has been right about early closes without a table like this one.",
        "Regenerate it rather than editing it.",
        "",
        "## Holidays",
        "",
        "Weekdays with no session.",
        "",
        "| date | day |",
        "|---|---|",
    ]
    lines += [f"| {day} | {day:%A} |" for day in shut] or ["| none | |"]
    lines += [
        "",
        "## Early closes",
        "",
        "The session opens as usual and closes early. A half day leaves roughly",
        "seven 30-minute bars instead of thirteen, which matters wherever a rule",
        "is justified by how many bars a day contains.",
        "",
        "| date | day | close |",
        "|---|---|---|",
    ]
    lines += [
        f"| {s.on} | {s.on:%A} | {s.closes:%H:%M} ET |" for s in early
    ] or ["| none | | |"]
    lines += [
        "",
        "## Closures the flatten does not cover",
        "",
        "Both flatten triggers are registered **Friday-only**, so a closure whose",
        "last session is not a Friday leaves the book open across it. Entries are",
        "still permitted on those days, because `wind_down_from_weekday` also",
        "tests the weekday rather than the calendar.",
        "",
        "Until `WORKLIST.md` §10 lands, each of these needs",
        "`python scripts/flatten.py --submit` run by hand before the bell.",
        "",
        "| last session | day | close | reopens | gap |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| **{c.last_session}** | {c.last_session:%A} | {c.closes:%H:%M} ET "
        f"| {c.reopens} | {c.days}d |"
        for c in missed
    ] or ["| none | | | | |"]
    lines += ["", "## Every closure of three days or more", "",
              "| last session | close | reopens | gap | covered |", "|---|---|---|---|---|"]
    missed_days = {c.last_session for c in missed}
    lines += [
        f"| {c.last_session:%a %Y-%m-%d} | {c.closes:%H:%M} | "
        f"{c.reopens:%a %Y-%m-%d} | {c.days}d | "
        f"{'**NO**' if c.last_session in missed_days else 'yes'} |"
        for c in closures(sessions)
    ]
    return "\n".join(lines) + "\n"


async def main(through: date | None, write: str | None) -> int:
    start = date.today()
    end = through or (start + timedelta(days=365))
    if end < start:
        print(f"{RED}--through is before today{RESET}")
        return 2

    try:
        sessions = await fetch(start, end)
    except BrokerError as exc:
        print(f"{RED}could not read the broker calendar: {exc}{RESET}")
        return 2
    if not sessions:
        print(f"{RED}the broker returned no sessions for {start}..{end}{RESET}")
        return 2

    print(f"{DIM}{len(sessions)} sessions, {start} to {end}{RESET}")

    shut = holidays(sessions, start, end)
    print(f"\n{BOLD}HOLIDAYS{RESET} {DIM}(weekdays with no session){RESET}")
    for day in shut:
        print(f"  {day:%a %Y-%m-%d}")

    early = [s for s in sessions if s.is_early_close]
    print(f"\n{BOLD}EARLY CLOSES{RESET}")
    for session in early:
        print(f"  {YELLOW}{session.label}{RESET}")

    missed = unflattened(sessions)
    print(f"\n{BOLD}CLOSURES THE FRIDAY-ONLY FLATTEN MISSES{RESET}")
    if not missed:
        print(f"  {GREEN}none in this range{RESET}")
    for closure in missed:
        print(f"  {RED}{closure.label}{RESET}")
        print(f"    {DIM}entries are allowed and no flatten runs — "
              f"flatten by hand before the bell{RESET}")

    if write:
        with open(write, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(_render(sessions, start, end))
        print(f"\n{GREEN}wrote {write}{RESET}")

    if missed:
        print(f"\n{YELLOW}{len(missed)} date(s) need a manual flatten. "
              f"The real fix is WORKLIST.md §10 and ends the window.{RESET}")
    return 0


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--through", type=date.fromisoformat, default=None,
                   metavar="YYYY-MM-DD", help="last day to report (default +365)")
    p.add_argument("--write", metavar="FILE",
                   help="also write the markdown reference to FILE")
    a = p.parse_args()
    raise SystemExit(asyncio.run(main(a.through, a.write)))
